// ─── Test 5: Tenant who started in the future is skipped ──────────────────
test('auto bill generator skips if tenant start_date is in the future', function () {
    $admin = User::factory()->create(['role' => 'admin', 'status' => 'approved']);
    $futureDate = now()->addMonth()->toDateString();
    [, $flat] = array_values(buildActiveFlat($admin, [], $futureDate));

    AutoBillGenerator::generateForUser($admin->id);

    expect(MonthlyBill::where('flat_id', $flat->id)->count())->toBe(0);
});

// ─── Test 6: Previous due is carried over from last bill ──────────────────
test('auto bill generator carries over previous_due from last unpaid bill', function () {
    $admin = User::factory()->create(['role' => 'admin', 'status' => 'approved']);
    [, $flat, $tenant, $flatTenant] = array_values(buildActiveFlat($admin));

    $lastMonth = now()->subMonth()->format('Y-m');
    [$ly, $lm] = explode('-', $lastMonth);

    // Create a previous unpaid bill with remaining_amount
    MonthlyBill::create([
        'flat_id'           => $flat->id,
        'building_id'       => $flat->building_id,
        'tenant_id'         => $tenant->id,
        'flat_tenant_id'    => $flatTenant->id,
        'bill_month'        => $lastMonth,
        'bill_year'         => (int) $ly,
        'bill_month_number' => (int) $lm,
        'house_rent'        => 5000,
        'wasa'              => 0, 'common_electricity' => 0, 'gas' => 0,
        'utility' => 0, 'parking' => 0, 'society_bill' => 0, 'security' => 0, 'other' => 0,
        'total_amount'      => 5000,
        'paid_amount'       => 2000,
        'remaining_amount'  => 3000, // ← 3000 BDT remaining
        'previous_due'      => 0,
        'collection_status' => 'partial',
        'generated_by'      => $admin->id,
    ]);

    AutoBillGenerator::generateForUser($admin->id);

    $currentMonth = now()->format('Y-m');
    $newBill = MonthlyBill::where('flat_id', $flat->id)
        ->where('bill_month', $currentMonth)
        ->first();

    expect($newBill)->not->toBeNull();
    expect((float) $newBill->previous_due)->toBe(3000.0);
    // remaining = total(5450) + previous_due(3000) = 8450
    expect((float) $newBill->remaining_amount)->toBe(8450.0);
});
